//! The Python driver: openEMS's documented Python interface (`CSXCAD.ContinuousStructure`,
//! `openEMS.openEMS`: `ReadFromXML`, `SetGaussExcite`, `SetBoundaryCond`, `AddLumpedPort`,
//! `AddMSLPort`, `Run`, `CalcPort`), one run per excited port, Touchstone output.

use std::fmt::Write as _;

use super::{Boundary, Options, Port, PortKind, mm};

const AXES: [&str; 3] = ["x", "y", "z"];

fn py_str(s: &str) -> String {
    let mut o = String::from("'");
    for c in s.chars() {
        match c {
            '\\' => o.push_str("\\\\"),
            '\'' => o.push_str("\\'"),
            '\n' => o.push_str("\\n"),
            c if (c as u32) < 0x20 => {
                let _ = write!(o, "\\x{:02x}", c as u32);
            }
            c => o.push(c),
        }
    }
    o.push('\'');
    o
}

fn point(p: [i64; 3]) -> String {
    format!("[{}, {}, {}]", mm(p[0]), mm(p[1]), mm(p[2]))
}

/// Frequencies of the Touchstone file: from `f_min` (or 1 % of `f_max` when 0: port
/// calculations are undefined at DC) to `f_max`.
pub(super) fn f_start(o: &Options) -> u64 {
    if o.f_min_hz > 0 { o.f_min_hz } else { (o.f_max_hz / 100).max(1) }
}

pub(super) fn write(o: &Options, ports: &[Port], touchstone: &str, f0: u64, fc: u64) -> String {
    let mut s = String::new();
    let bc = match o.boundary {
        Boundary::Pml => format!("'PML_{}'", o.pml_cells),
        Boundary::Mur => "'MUR'".to_string(),
    };
    let title = if o.title.is_empty() { String::new() } else { format!(" for {}", o.title.replace('"', "'")) };
    let _ = write!(
        s,
        r#"#!/usr/bin/env python3
"""openEMS driver generated by cadlab `export.openems`{title}.

Runs one FDTD simulation per port (that port excited, the others terminated in their reference
impedance) on the geometry and mesh of {xml}, then writes the S-parameters to {ts}
(Touchstone). Requires openEMS with its Python interface (the CSXCAD and openEMS modules) and
numpy. Lengths are in mm, frequencies in Hz.

Usage: python3 {py}               simulate, then write {ts}
       python3 {py} --postprocess  only recompute {ts} from earlier runs
"""

import os
import sys

import numpy as np
from CSXCAD import ContinuousStructure
from openEMS import openEMS

HERE = os.path.dirname(os.path.abspath(__file__))
GEOMETRY = os.path.join(HERE, {xml_q})
SIM_DIR = os.path.join(HERE, {sim_q})
TOUCHSTONE = os.path.join(HERE, {ts_q})

F_START = {f_start}
F_STOP = {f_stop}
POINTS = {points}
# Gaussian pulse: centre F0, 20 dB half-bandwidth FC (covers F0 - FC .. F0 + FC).
F0 = {f0}
FC = {fc}
BOUNDARY = [{bc}] * 6
END_CRITERIA = 10 ** (-{end_db} / 10)  # stop when the energy has decayed by {end_db} dB
MAX_TIMESTEPS = {steps}

"#,
        xml = format_args!("{}.xml", o.name),
        py = format_args!("{}.py", o.name),
        ts = touchstone,
        xml_q = py_str(&format!("{}.xml", o.name)),
        sim_q = py_str(&format!("{}_sim", o.name)),
        ts_q = py_str(touchstone),
        f_start = f_start(o),
        f_stop = o.f_max_hz,
        points = o.points,
        steps = o.timesteps,
        end_db = o.end_criteria_db,
    );
    let _ = writeln!(s, "# Ports, numbered from 1 (start/stop in mm; z0 in ohms).");
    let _ = writeln!(s, "PORTS = [");
    for p in ports {
        let i = &p.info;
        let _ = writeln!(s, "    # {}: {} on {} over {}", i.number, i.at, i.layer, i.reference);
        match i.kind {
            PortKind::Lumped => {
                let _ = writeln!(
                    s,
                    "    {{'kind': 'lumped', 'z0': {}, 'start': {}, 'stop': {}, 'dir': 'z'}},",
                    i.z0.with_unit(crate::value::Unit::None),
                    point(p.start),
                    point(p.stop)
                );
            }
            PortKind::Msl => {
                let _ = writeln!(
                    s,
                    "    {{'kind': 'msl', 'z0': {}, 'start': {}, 'stop': {}, 'prop': '{}', 'dir': 'z',\n     'feed_shift': {}, 'meas_shift': {}}},",
                    i.z0.with_unit(crate::value::Unit::None),
                    point(p.start),
                    point(p.stop),
                    AXES[p.prop],
                    mm(p.feed_shift),
                    mm(p.meas_shift)
                );
            }
        }
    }
    let _ = writeln!(s, "]");
    s.push_str(
        r#"

def simulate(excited, run):
    """Sets up the run exciting port `excited` (0-based), runs it if `run`; returns its
    directory and the port objects."""
    path = os.path.join(SIM_DIR, 'port%d' % (excited + 1))
    fdtd = openEMS(NrTS=MAX_TIMESTEPS, EndCriteria=END_CRITERIA)
    fdtd.SetGaussExcite(F0, FC)
    fdtd.SetBoundaryCond(BOUNDARY)
    csx = ContinuousStructure()
    csx.ReadFromXML(GEOMETRY)
    fdtd.SetCSX(csx)
    ports = []
    for i, p in enumerate(PORTS):
        excite = 1.0 if i == excited else 0.0
        if p['kind'] == 'lumped':
            port = fdtd.AddLumpedPort(i + 1, p['z0'], p['start'], p['stop'], p['dir'], excite, priority=5)
        else:
            metal = csx.AddMetal('msl_port_%d' % (i + 1))
            port = fdtd.AddMSLPort(i + 1, metal, p['start'], p['stop'], p['prop'], p['dir'], excite=-excite,
                                   FeedShift=p['feed_shift'], MeasPlaneShift=p['meas_shift'], priority=10)
        ports.append(port)
    if run:
        fdtd.Run(path, cleanup=True)
    return path, ports


def write_touchstone(path, f, s, z0):
    """Touchstone 1.1 (one reference impedance) or 2.0 (one per port), real/imaginary."""
    n = s.shape[1]
    v2 = any(z != z0[0] for z in z0)
    with open(path, 'w') as out:
        if v2:
            out.write('[Version] 2.0\n')
        out.write('! S-parameters computed by openEMS; model exported by cadlab\n')
        out.write('# Hz S RI R %g\n' % z0[0])
        if v2:
            out.write('[Number of Ports] %d\n' % n)
            if n == 2:
                out.write('[Two-Port Data Order] 21_12\n')
            out.write('[Number of Frequencies] %d\n' % len(f))
            out.write('[Reference] %s\n' % ' '.join('%g' % z for z in z0))
            out.write('[Network Data]\n')
        pair = lambda v: '%.9g %.9g' % (v.real, v.imag)
        for k in range(len(f)):
            if n == 2:
                vals = [s[k, 0, 0], s[k, 1, 0], s[k, 0, 1], s[k, 1, 1]]
                out.write('%.9g %s\n' % (f[k], ' '.join(pair(v) for v in vals)))
                continue
            for i in range(n):
                for c in range(0, n, 4):
                    lead = ('%.9g' % f[k]) if i == 0 and c == 0 else ' '
                    out.write('%s %s\n' % (lead, ' '.join(pair(v) for v in s[k, i, c:c + 4])))
        if v2:
            out.write('[End]\n')


def main():
    run = '--postprocess' not in sys.argv[1:]
    f = np.linspace(F_START, F_STOP, POINTS)
    n = len(PORTS)
    s = np.zeros((len(f), n, n), dtype=complex)
    for j in range(n):
        path, ports = simulate(j, run)
        for i, port in enumerate(ports):
            port.CalcPort(path, f, ref_impedance=PORTS[i]['z0'])
        for i in range(n):
            s[:, i, j] = ports[i].uf_ref / ports[j].uf_inc
    write_touchstone(TOUCHSTONE, f, s, [p['z0'] for p in PORTS])
    print('wrote', TOUCHSTONE)


if __name__ == '__main__':
    main()
"#,
    );
    s
}
